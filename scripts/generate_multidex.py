#!/usr/bin/env python3
"""Render Multidex's product page and notices from checked-in content.

Multidex's notices are authored here in content/multidex/. The app's own web build
owns /multidex/, so these pages live at /multidex-app/. Sitemap entries are
hand-maintained like other projects' entries and must stay before Bounty's block.
  python3 scripts/generate_multidex.py
  python3 scripts/generate_multidex.py --check
"""

import argparse
from datetime import date
import hashlib
from html import escape
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content" / "multidex" / "content.json"
MARKETING = CONTENT.with_name("marketing.json")
SITE = ROOT / "site" / "multidex-app"
ORIGIN = "https://kunal26das.github.io"
BASE = "/multidex-app/"
SLUGS = ("privacy", "terms", "subscriptions", "support", "delete-account")
ICON_512 = SITE / "multidex-icon-512.png"
ICON_180 = SITE / "multidex-icon-180.png"


def load_brand_version():
    for icon in (ICON_512, ICON_180):
        if not icon.is_file():
            raise SystemExit(f"Missing Multidex icon: {icon.relative_to(ROOT)}")
    return hashlib.sha256(ICON_512.read_bytes()).hexdigest()[:12]


BRAND_VERSION = load_brand_version()


def load_content():
    data = json.loads(CONTENT.read_text())
    if data["schemaVersion"] != 1 or not isinstance(data["isDraft"], bool):
        raise SystemExit("Unsupported Multidex notice schema.")
    if tuple(document["slug"] for document in data["documents"]) != SLUGS:
        raise SystemExit("Multidex notice routes changed; review the generator first.")
    return data


def load_marketing(data):
    marketing = json.loads(MARKETING.read_text())
    expected_play_url = f'https://play.google.com/store/apps/details?id={data["appId"]}'
    if marketing.get("schemaVersion") != 1 or marketing.get("playUrl") != expected_play_url:
        raise SystemExit("Unsupported Multidex product content or Google Play app identifier.")
    date.fromisoformat(marketing["updatedOn"])
    return marketing


def icon(size):
    path = ICON_512 if size > 180 else ICON_180
    return f"{BASE}{path.name}?v={BRAND_VERSION}"


def document_links(data, current=None):
    links = []
    for document in data["documents"]:
        selected = ' aria-current="page"' if document["slug"] == current else ""
        links.append(f'<a href="{BASE}{document["slug"]}/"{selected}>{escape(document["title"])}</a>')
    return "\n                ".join(links)


def structured_data(data, title, description, path):
    app_id = f"{ORIGIN}{BASE}#app"
    graph = [{
        "@type": "WebPage", "@id": f"{ORIGIN}{path}#webpage",
        "url": f"{ORIGIN}{path}", "name": title, "description": description,
        "inLanguage": "en", "about": {"@id": app_id},
    }]
    if path == BASE:
        graph.insert(0, {
            "@type": "MobileApplication", "@id": app_id, "name": data["storeTitle"],
            "url": f"{ORIGIN}{BASE}", "operatingSystem": "Android",
            "applicationCategory": "ReferenceApplication", "description": description,
            "image": f"{ORIGIN}{icon(512)}",
            "installUrl": f'https://play.google.com/store/apps/details?id={data["appId"]}',
            "creator": {"@type": "Person", "name": data["operatorName"]},
        })
    return json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, indent=4).replace("<", "\\u003c")


