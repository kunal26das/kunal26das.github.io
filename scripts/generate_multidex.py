def status_notice(data):
    if not data["isDraft"]:
        return ""
    return f'''    <aside class="multidex-status" aria-label="Publication status">
        <span class="multidex-label">Draft preview</span>
        <p>{escape(data["draftNotice"])}</p>
    </aside>'''


def contents(document, mobile=False):
    links = "\n".join(f'            <li><a href="#section-{index}">{escape(section["heading"])}</a></li>' for index, section in enumerate(document["sections"], 1))
    nav = f'<nav aria-label="On this page"><ol>\n{links}\n        </ol></nav>'
    if mobile:
        return f'    <details class="toc-mobile"><summary>On this page</summary>{nav}</details>'
    return f'        <aside class="toc"><p class="toc-title">On this page</p>{nav}</aside>'


def render_document(data, document):
    sections = []
    for index, section in enumerate(document["sections"], 1):
        paragraphs = "\n".join(f'            <p>{escape(paragraph)}</p>' for paragraph in section["paragraphs"])
        sections.append(f'            <h2 id="section-{index}">{escape(section["heading"])}</h2>\n{paragraphs}')
    contact = ""
    if document["slug"] in {"support", "delete-account"}:
        subject = "Multidex%20account%20deletion" if document["slug"] == "delete-account" else "Multidex%20support"
        label = "Prepare a deletion request email" if document["slug"] == "delete-account" else "Prepare a support email"
        contact = f'''\n            <div class="multidex-contact"><a class="multidex-contact-link" href="mailto:{escape(data["supportEmail"], quote=True)}?subject={subject}">{label} <span aria-hidden="true">↗</span></a><p>Opens your email app. Review the message before sending; no request is submitted by this page. Sending a message does not confirm deletion or cancel a subscription.</p></div>'''
    label = "Draft notice" if data["isDraft"] else "Multidex notice"
    body = f'''    <header class="article-header">
        <a class="back-link" href="{BASE}">← Multidex information</a>
        <p class="eyebrow multidex-eyebrow"><a class="multidex-app-brand" href="{BASE}"><img src="{icon(180)}" width="32" height="32" alt=""><span>Multidex</span></a><span aria-hidden="true">·</span><span>{label}</span></p>
        <h1 class="article-title" id="document-title">{escape(document["title"])}<span class="multidex-title-dot">.</span></h1>
        <p class="article-subtitle">{escape(document["summary"])}</p>
        <div class="article-meta"><span>Content reviewed {escape(data["reviewedOn"])}</span><span>{escape(data["storeTitle"])} · {escape(data["developerName"])}</span><span>{escape(data["appId"])}</span></div>
    </header>
{status_notice(data)}
    <nav class="multidex-document-nav" aria-label="Multidex documents">{document_links(data, document["slug"])}</nav>
{contents(document, mobile=True)}
    <div class="reading-layout">
{contents(document)}
        <article class="prose" aria-labelledby="document-title">
{chr(10).join(sections)}{contact}
            <div class="article-end"><a href="{BASE}">← All Multidex information</a><a href="{BASE}support/">Get help ↗</a></div>
        </article>
    </div>'''
    return layout(data, document["title"], document["summary"], f'{BASE}{document["slug"]}/', body)


