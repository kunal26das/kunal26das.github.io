def rendered_pages(data):
    return {SITE / "index.html": render_hub(data, load_marketing(data)), **{
        SITE / document["slug"] / "index.html": render_document(data, document)
        for document in data["documents"]
    }}


def check():
    data = load_content()
    pages = rendered_pages(data)
    stale = [str(path.relative_to(ROOT)) for path, text in pages.items() if not path.is_file() or path.read_text() != text]
    if stale:
        raise SystemExit("Multidex pages need regeneration:\n" + "\n".join(stale))
    print("Verified six Multidex pages.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        check()
    else:
        for path, text in rendered_pages(load_content()).items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        print("Rendered Multidex's product page and five notices.")


if __name__ == "__main__":
    main()
