#!/usr/bin/env python3
"""Render Bounty's product page and approved notices from checked-in content.

Normal generation/checks are self-contained. To refresh the snapshot explicitly:
  python3 scripts/generate_bounty.py --import-json /path/to/bounty/legal/content.json \
    --source-revision COMMIT_SHA --snapshot-date YYYY-MM-DD
  python3 scripts/generate_bounty.py --check
"""

import argparse
from datetime import date, datetime
import hashlib
from html import escape
import json
from pathlib import Path
import re
import shutil


ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content" / "bounty" / "content.json"
PROVENANCE = CONTENT.with_name("provenance.json")
MARKETING = CONTENT.with_name("marketing.json")
SITEMAP = ROOT / "site" / "sitemap.xml"
ORIGIN = "https://kunal26das.github.io"
SLUGS = ("privacy", "terms", "subscriptions", "support", "delete-account")


def load_brand_version():
    brand_root = ROOT / "site" / "bounty"
    brand = json.loads((brand_root / "brand-assets.json").read_text())
    expected = {"bounty-icon.svg", "bounty-icon-180.png", "bounty-icon-512.png"}
    if brand["brandMaster"] != "design/brand/bounty-icon.svg" or {item["file"] for item in brand["files"]} != expected or len(brand["files"]) != len(expected):
        raise SystemExit("Unsupported Bounty brand asset manifest.")
    for item in brand["files"]:
        asset = (brand_root / item["file"]).read_bytes()
        if len(asset) != item["bytes"] or hashlib.sha256(asset).hexdigest() != item["sha256"]:
            raise SystemExit(f"Bounty brand asset does not match its provenance: {item['file']}")
    svg_hash = hashlib.sha256((brand_root / "bounty-icon.svg").read_bytes()).hexdigest()
    if svg_hash != brand["brandSha256"]:
        raise SystemExit("Bounty website icon does not match its approved master hash.")
    return brand["brandSha256"][:12]


BRAND_VERSION = load_brand_version()


def load_content():
    content_bytes = CONTENT.read_bytes()
    data = json.loads(content_bytes)
    provenance = json.loads(PROVENANCE.read_text())
    if hashlib.sha256(content_bytes).hexdigest() != provenance["sha256"]:
        raise SystemExit("Bounty content snapshot does not match its provenance hash.")
    if data["schemaVersion"] != 1 or not isinstance(data["isDraft"], bool):
        raise SystemExit("Unsupported Bounty notice schema.")
    if tuple(document["slug"] for document in data["documents"]) != SLUGS:
        raise SystemExit("Bounty notice routes changed; review the generator first.")
    return data


def document_links(data, current=None):
    links = []
    for document in data["documents"]:
        selected = ' aria-current="page"' if document["slug"] == current else ""
        links.append(f'<a href="/bounty/{document["slug"]}/"{selected}>{escape(document["title"])}</a>')
    return "\n                ".join(links)


def load_marketing(data):
    marketing = json.loads(MARKETING.read_text())
    expected_play_url = f'https://play.google.com/store/apps/details?id={data["appId"]}'
    if marketing.get("schemaVersion") != 1 or marketing.get("playUrl") != expected_play_url:
        raise SystemExit("Unsupported Bounty product content or Google Play app identifier.")
    date.fromisoformat(marketing["updatedOn"])
    return marketing


def structured_data(data, title, description, path):
    app_id = f"{ORIGIN}/bounty/#app"
    graph = [{
        "@type": "WebPage", "@id": f"{ORIGIN}{path}#webpage",
        "url": f"{ORIGIN}{path}", "name": title, "description": description,
        "inLanguage": "en", "about": {"@id": app_id},
    }]
    if path == "/bounty/":
        graph.insert(0, {
            "@type": "MobileApplication", "@id": app_id, "name": data["appName"],
            "url": f"{ORIGIN}/bounty/", "operatingSystem": "Android",
            "applicationCategory": "FinanceApplication", "description": description,
            "image": f"{ORIGIN}/bounty/bounty-icon-512.png?v={BRAND_VERSION}",
            "installUrl": f'https://play.google.com/store/apps/details?id={data["appId"]}',
            "creator": {"@type": "Person", "name": data["operatorName"]},
        })
    return json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, indent=4).replace("<", "\\u003c")


