def rendered_pages(data):
    return {ROOT / "site" / "bounty" / "index.html": render_hub(data, load_marketing(data)), **{
        ROOT / "site" / "bounty" / document["slug"] / "index.html": render_document(data, document)
        for document in data["documents"]
    }}


def rendered_sitemap(data):
    """Own only Bounty entries; retain other projects' hand-maintained metadata."""
    source = SITEMAP.read_text()
    routes = ["/bounty/", *(f"/bounty/{slug}/" for slug in SLUGS)]
    urls = {f"{ORIGIN}{route}" for route in routes}

    def retain_other_routes(match):
        location = re.search(r"<loc>([^<]+)</loc>", match.group())
        return "" if location and location[1] in urls else match.group()

    source = re.sub(r"    <url>\n.*?    </url>\n", retain_other_routes, source, flags=re.DOTALL)
    if source.count("</urlset>") != 1:
        raise SystemExit("Unsupported sitemap format; Bounty entries could not be synchronized.")
    entries = []
    if not data["isDraft"]:
        marketing_date = load_marketing(data)["updatedOn"]
        notice_date = datetime.strptime(data["reviewedOn"], "%d %B %Y").date().isoformat()
        for route in routes:
            modified = marketing_date if route == "/bounty/" else notice_date
            entries.append(f"    <url>\n        <loc>{ORIGIN}{route}</loc>\n        <lastmod>{modified}</lastmod>\n    </url>\n")
    return source.replace("</urlset>", "".join(entries) + "</urlset>")


def check():
    data = load_content()
    pages = {**rendered_pages(data), SITEMAP: rendered_sitemap(data)}
    stale = [str(path.relative_to(ROOT)) for path, text in pages.items() if not path.is_file() or path.read_text() != text]
    if stale:
        raise SystemExit("Bounty pages or sitemap need regeneration:\n" + "\n".join(stale))
    print("Verified six Bounty pages, content provenance and final/draft sitemap state.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--import-json", type=Path)
    parser.add_argument("--source-revision")
    parser.add_argument("--snapshot-date")
    args = parser.parse_args()
    if args.import_json:
        if args.check or not re.fullmatch(r"[a-f0-9]{40}", args.source_revision or "") or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", args.snapshot_date or ""):
            parser.error("Import requires --source-revision (full commit SHA) and --snapshot-date (YYYY-MM-DD), without --check.")
        # Import happens only on an explicit authoring command, never on a site build.
        content = json.loads(args.import_json.read_text())
        if content.get("schemaVersion") != 1 or not isinstance(content.get("isDraft"), bool):
            parser.error("Unsupported canonical content schema.")
        CONTENT.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(args.import_json, CONTENT)
        provenance = {"sourceProject": "Bounty", "sourcePath": "legal/content.json", "sourceRevision": args.source_revision,
            "snapshotDate": args.snapshot_date, "sha256": hashlib.sha256(CONTENT.read_bytes()).hexdigest()}
        PROVENANCE.write_text(json.dumps(provenance, indent=2) + "\n")
    if args.check:
        check()
    else:
        data = load_content()
        for path, text in {**rendered_pages(data), SITEMAP: rendered_sitemap(data)}.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        print("Rendered Bounty's product page, five notices and final/draft sitemap entries.")


if __name__ == "__main__":
    main()
